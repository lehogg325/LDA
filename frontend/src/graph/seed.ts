// Deterministic hashing for stable jitter and tie-breaking (the orbit layout must
// produce identical coordinates for identical data, across sessions).

export function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
